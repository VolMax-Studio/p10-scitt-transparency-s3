"""Separate application report (never a replacement verdict) and the export archive with an artifact allowlist."""
import hashlib
import io
import json
import os
import secrets
import shutil
import stat
import subprocess
import tarfile
import tempfile

APP_VERSION = "0.1.3"
APP_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE_GLOBS = ("run.py", "workbench", "static", "profiles")

# job-relative path -> name inside the export archive. Nothing outside this allowlist is exported or served.
ARTIFACTS = {
    "app-report.json": "app-report.json",
    "readiness.json": "readiness.json",
    "result.json": "result.json",
    "stdout.log": "logs/wrapper-stdout.log",
    "stderr.log": "logs/wrapper-stderr.log",
    "runner-out/verdict.json": "runner/verdict.json",
    "runner-out/run-info.json": "runner/run-info.json",
    "runner-out/preflight.json": "runner/preflight.json",
    "runner-out/stdout.txt": "runner/stdout.txt",
    "profile.json": "profile.json",
}
# URL names accepted by GET /api/runs/<id>/artifacts/<name>
SERVED = {
    "verdict.json": "runner-out/verdict.json", "run-info.json": "runner-out/run-info.json", "preflight.json": "runner-out/preflight.json",
    "runner-stdout.txt": "runner-out/stdout.txt", "stdout.log": "stdout.log", "stderr.log": "stderr.log",
    "readiness.json": "readiness.json", "app-report.json": "app-report.json", "result.json": "result.json",
}
MAX_SERVED = 8 * 1024 * 1024


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def source_identity(app_dir=APP_DIR):
    lines = []
    for g in SOURCE_GLOBS:
        base = os.path.join(app_dir, g)
        paths = [base] if os.path.isfile(base) else [os.path.join(r, f) for r, _, fs in os.walk(base) for f in fs if "__pycache__" not in r]
        for p in sorted(paths):
            lines.append(f"{sha256_file(p)}  {os.path.relpath(p, app_dir)}")
    ident = {"app_version": APP_VERSION, "source_listing_sha256": hashlib.sha256(("\n".join(lines) + "\n").encode()).hexdigest(), "files": len(lines)}
    try:
        top = subprocess.run(["git", "-C", app_dir, "rev-parse", "HEAD"], capture_output=True, text=True, timeout=10)
        if top.returncode == 0:
            ident["git_head"] = top.stdout.strip()
            dirty = subprocess.run(["git", "-C", app_dir, "status", "--porcelain", "--", "."], capture_output=True, text=True, timeout=10)
            ident["git_dirty_under_app"] = bool(dirty.stdout.strip())
    except (OSError, subprocess.SubprocessError):
        pass
    return ident


def write_atomic(path, data):
    tmp = f"{path}.tmp{os.getpid()}"
    with open(tmp, "wb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


LIMITATIONS = [
    "This report was generated by the Replay Workbench application and is not an independent attestation.",
    "BINDING_MATCH concerns the authenticated capture and the frozen chain; it is not evidence of scientific truth, policy enforcement, full RFC 9943/SCRAPI compliance or independent operators.",
    "The three axes (application execution, P10 runner outcome, accepted-reference reproduction) are independent; the wrapper exit status is not a P10 outcome.",
    "Logs and records may contain local host names and paths; exporting is an operator action.",
    "Readiness observations are advisory; the wrapper and runner repeat their own checks.",
]


def build_report(job_dir, spec, result):
    arts = {}
    for rel in ARTIFACTS:
        p = os.path.join(job_dir, rel)
        if rel != "app-report.json" and os.path.isfile(p):
            arts[rel] = {"sha256": sha256_file(p), "bytes": os.path.getsize(p)}
    desc = spec.get("module_description", {})
    return {
        "format": "p10-replay-workbench-report-v0", "not_a_verdict": True,
        "app": source_identity(), "profile": {"id": desc.get("profile_id"), "sha256": desc.get("profile_sha256"), "archive_sha256": desc.get("archive_sha256")},
        "execution_kind": desc.get("execution_kind"), "synthetic": bool(desc.get("synthetic")),
        "job": {"id": spec["job_id"], "kind": spec["kind"], "package_id": spec.get("package_id"), "deadline_seconds": spec["deadline_s"],
                "log_limit_bytes": spec["log_limit"], "created": spec.get("created"), "finished": result.get("finished"), "elapsed_seconds": result.get("elapsed_seconds")},
        "command": result.get("command"), "wrapper_exit": result.get("wrapper_exit"), "wrapper_exit_meaning": result.get("wrapper_exit_meaning"),
        "supervision": result.get("supervision"),
        "axes": {"application_execution": result.get("execution"), "p10_runner_outcome": result.get("p10"), "accepted_reference_reproduction": result.get("reproduction")},
        "readiness": result.get("readiness"), "signature": {"allowed_signers_sha256": (result.get("signers") or {}).get("sha256"),
                                                          "checked": bool(result.get("signers"))},
        "raw_artifacts": arts, "record_artifacts": result.get("artifacts"),
        "host": {"resource_settings": None}, "limitations": LIMITATIONS,
    }


def finalize(job_dir, spec, result):
    with open(os.path.join(job_dir, "profile.json"), "wb") as f:
        f.write(json.dumps(spec.get("profile", {}), indent=1, sort_keys=True).encode() + b"\n")
    rep = build_report(job_dir, spec, result)
    try:
        with open(os.path.join(job_dir, "status.json")) as f:
            rep["host"]["resource_settings"] = json.load(f).get("resources")
    except (OSError, ValueError):
        pass
    write_atomic(os.path.join(job_dir, "app-report.json"), json.dumps(rep, indent=1, sort_keys=True).encode() + b"\n")


def snapshot_file(path, dest_dir):
    """Copy one stable prefix of `path` into a private temp file; return (tmp_path, size, sha256) or None.

    The size is fixed from fstat at open time and exactly that many bytes are copied and hashed in one pass, so bytes appended
    afterwards (a log of a running job) cannot make the hash and the archived bytes differ. Symlinks and non-regular files are refused.
    """
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    except OSError:
        return None
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode):
            return None
        want, h = st.st_size, hashlib.sha256()
        tmp = os.path.join(dest_dir, "snap-" + secrets.token_hex(8))
        out = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        got = 0
        with os.fdopen(out, "wb") as o:
            while got < want:
                b = os.read(fd, min(1 << 20, want - got))
                if not b:
                    break
                h.update(b)
                o.write(b)
                got += len(b)
        return tmp, got, h.hexdigest()
    finally:
        os.close(fd)


def export_archive(job_dir, tmp_dir=None, partial=False, _after_snapshot=None):
    """Return bytes of a tar.gz containing only allowlisted job artifacts, REPORT_SHA256SUMS and export-info.json.

    Every artifact is snapshotted once; the hash in REPORT_SHA256SUMS and the archived bytes come from that same snapshot.
    `partial` records that the job had no final result when the export was made.
    """
    tmp_dir = tmp_dir or tempfile.gettempdir()
    work = tempfile.mkdtemp(prefix="export-", dir=tmp_dir)
    try:
        snaps = []
        for rel, name in sorted(ARTIFACTS.items(), key=lambda kv: kv[1]):
            sn = snapshot_file(os.path.join(job_dir, rel), work)
            if sn:
                snaps.append((name, *sn))
        if _after_snapshot:
            _after_snapshot()
        info = json.dumps({"format": "p10-replay-workbench-export-v0", "app_version": APP_VERSION, "job_had_final_result": not partial,
                           "note": "each file is one stable snapshot; logs of a running job may be incomplete",
                           "files": {n: {"bytes": size, "sha256": h} for n, _, size, h in snaps}}, indent=1, sort_keys=True).encode() + b"\n"
        sums = "".join(f"{h}  {n}\n" for n, _, _, h in snaps).encode()
        sums += f"{hashlib.sha256(info).hexdigest()}  export-info.json\n".encode()
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode="w:gz") as tf:
            def add_bytes(n, data):
                ti = tarfile.TarInfo("replay-report/" + n)
                ti.mode, ti.uid, ti.gid, ti.uname, ti.gname, ti.size, ti.mtime = 0o644, 0, 0, "", "", len(data), 0
                tf.addfile(ti, io.BytesIO(data))
            for n, p, size, h in snaps:
                ti = tarfile.TarInfo("replay-report/" + n)
                ti.mode, ti.uid, ti.gid, ti.uname, ti.gname, ti.size, ti.mtime = 0o644, 0, 0, "", "", size, 0
                with open(p, "rb") as f:
                    tf.addfile(ti, f)
            add_bytes("export-info.json", info)
            add_bytes("REPORT_SHA256SUMS", sums)
        return buf.getvalue()
    finally:
        shutil.rmtree(work, ignore_errors=True)


def read_served(job_dir, name):
    """Bytes of an allowlisted artifact (last MAX_SERVED bytes if larger), or None."""
    rel = SERVED.get(name)
    if rel is None:
        return None
    p = os.path.join(job_dir, rel)
    if not os.path.isfile(p) or os.path.islink(p):
        return None
    size = os.path.getsize(p)
    with open(p, "rb") as f:
        if size > MAX_SERVED:
            f.seek(size - MAX_SERVED)
        return f.read(MAX_SERVED)
